using System;
using System.Collections.Generic;
using System.IO;
using CapFrameX.Video.Decoding;
using CapFrameX.Video.Overlay;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace CapFrameX.Video.Test;

/// <summary>
/// End-to-end tests for <see cref="OverlayBurn"/>: real burn of
/// <c>clip_vfr.mp4</c> (90 frames, 640x360, VFR) through decode → composite →
/// encode, checked against the reference CLI burn in <c>TestAssets/burn</c>.
/// </summary>
/// <remarks>
/// The pixel assertions exist to catch geometry regressions: the blend once
/// dropped the <c>x0</c> offset and silently drew the panel flush-left while
/// every frame-count and file-size check kept passing.
/// </remarks>
[TestClass]
public class OverlayBurnE2ETests
{
    private const string SourceClip = "clip_vfr.mp4";
    private const int Frames = 90;
    private const int W = 640;
    private const int H = 360;

    // Default style: position "br", margin 16, graph on, font_scale 1 →
    // panel 390x216 at (234, 128).
    private const int Px0 = W - 390 - 16;
    private const int Py0 = H - 216 - 16;
    private const int Pw = 390;
    private const int Ph = 216;

    // PanelBg #0a0c10 — the opaque interior of the rounded panel.
    private static readonly byte[] PanelBg = { 10, 12, 16 };

    private static string _outDir = null!;

    private static string Video(string name) => Path.Combine("TestVideos", name);

    private static string Reference() => Path.Combine("TestAssets", "burn", "clip_vfr_ref.mkv");

    [ClassInitialize]
    public static void VerifyPrerequisites(TestContext _)
    {
        Assert.IsTrue(File.Exists(Video(SourceClip)),
            $"missing test media '{SourceClip}' in TestVideos");
        Assert.IsTrue(File.Exists(Reference()),
            "missing reference burn 'TestAssets/burn/clip_vfr_ref.mkv' " +
            "(generated by the fps-analyzer Python pipeline)");
        Assert.IsTrue(FfmpegNative.ResolveRoot() != null,
            "FFmpeg shared libraries not found; run scripts/Get-FfmpegNative.ps1");
        _outDir = Path.Combine(Path.GetTempPath(), "capframex-burn-e2e", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_outDir);
    }

    [ClassCleanup]
    public static void Cleanup()
    {
        try { if (Directory.Exists(_outDir)) Directory.Delete(_outDir, recursive: true); }
        catch (IOException) { /* best effort */ }
    }

    private static BurnResult BurnLossless()
        => OverlayBurn.Burn(Video(SourceClip), Path.Combine(_outDir, "out.mkv"),
            declaredFps: 0, lossless: true);

    private static BurnResult BurnLossy()
        => OverlayBurn.Burn(Video(SourceClip), Path.Combine(_outDir, "out.mp4"),
            declaredFps: 0, lossless: false);

    private static List<byte[]> DecodeAll(string path)
    {
        var frames = new List<byte[]>();
        using var dec = new FfmpegFrameDecoder(path);
        Assert.AreEqual(W, dec.Width, $"{path}: unexpected width");
        Assert.AreEqual(H, dec.Height, $"{path}: unexpected height");
        var buf = new byte[W * H * 3];
        while (dec.TryReadNext(buf, out _, out _))
            frames.Add((byte[])buf.Clone());
        return frames;
    }

    private static bool IsPanelBg(byte[] frame, int x, int y)
    {
        int i = (y * W + x) * 3;
        return frame[i] == PanelBg[0] && frame[i + 1] == PanelBg[1] && frame[i + 2] == PanelBg[2];
    }

    private static int MaxChannelDiff(byte[] a, byte[] b, int x, int y)
    {
        int i = (y * W + x) * 3;
        return Math.Max(Math.Abs(a[i] - b[i]),
               Math.Max(Math.Abs(a[i + 1] - b[i + 1]), Math.Abs(a[i + 2] - b[i + 2])));
    }

    [TestMethod]
    public void Burn_Lossless_MatchesReferenceOutsidePanel()
    {
        var res = BurnLossless();
        Assert.AreEqual(Frames, res.Frames, "burn must emit one output frame per source frame");
        Assert.IsTrue(res.OutputPath.EndsWith(".mkv", StringComparison.OrdinalIgnoreCase),
            "lossless burn must be forced to .mkv");
        Assert.IsTrue(new FileInfo(res.OutputPath).Length > 10_000, "output looks empty");

        var mine = DecodeAll(res.OutputPath);
        var theirs = DecodeAll(Reference());
        Assert.AreEqual(Frames, mine.Count, "decoded burn has wrong frame count");
        Assert.AreEqual(theirs.Count, mine.Count, "burn and reference frame counts differ");

        // Sample frames: first, middle, last.
        foreach (var idx in new[] { 0, mine.Count / 2, mine.Count - 1 })
        {
            long sum = 0;
            int n = 0;
            int beyond2 = 0;
            for (int y = 0; y < H; y++)
            {
                for (int x = 0; x < W; x++)
                {
                    bool inPanel = y >= Py0 && y < Py0 + Ph && x >= Px0 && x < Px0 + Pw;
                    if (inPanel) continue;
                    int d = MaxChannelDiff(mine[idx], theirs[idx], x, y);
                    sum += d;
                    n++;
                    if (d > 2) beyond2++;
                }
            }
            double mean = sum / (double)n;
            double frac = beyond2 / (double)n;
            Assert.IsTrue(mean < 1.0,
                $"frame {idx}: outside-panel mean diff {mean:0.000} (panel geometry wrong?); reference vs burn should differ only by lossless round-trip noise");
            Assert.IsTrue(frac <= 0.001,
                $"frame {idx}: {frac * 100.0:0.00}% of outside-panel pixels differ by >2");
        }
    }

    [TestMethod]
    public void Burn_Lossless_PanelLandsExactlyAtStyleAnchor()
    {
        var res = BurnLossless();
        var frames = DecodeAll(res.OutputPath);
        Assert.AreEqual(Frames, frames.Count);

        byte[] f = frames[0];

        // 1) Opaque panel interior pixels must be PanelBg, exactly (FFV1 is
        //    lossless). (6,6) local: inside the r=10 corner circle, clear of
        //    the 0.5px border. (195,108) local: between the text block and
        //    the graph top — plain background.
        Assert.IsTrue(IsPanelBg(f, Px0 + 6, Py0 + 6),
            $"panel top-left corner at ({Px0 + 6},{Py0 + 6}) is not PanelBg — panel is not at its anchor");
        Assert.IsTrue(IsPanelBg(f, Px0 + 195, Py0 + 108),
            $"panel interior at ({Px0 + 195},{Py0 + 108}) is not PanelBg");

        // 2) The regression guard: pixels just OUTSIDE the anchor box must be
        //    video, not panel. If the blend drops x0 (panel drawn flush-left),
        //    these become PanelBg/GraphBg and this fails.
        Assert.IsFalse(IsPanelBg(f, Px0 - 6, Py0 + 108),
            "pixel left of the panel anchor is PanelBg — panel drawn outside its anchor box");
        Assert.IsFalse(IsPanelBg(f, Px0 + Pw + 6, Py0 + 108),
            "pixel right of the panel anchor is PanelBg — panel drawn outside its anchor box");
        Assert.IsFalse(IsPanelBg(f, Px0 + 195, Py0 - 6),
            "pixel above the panel anchor is PanelBg — panel drawn outside its anchor box");
        Assert.IsFalse(IsPanelBg(f, Px0 + 195, Py0 + Ph + 6),
            "pixel below the panel anchor is PanelBg — panel drawn outside its anchor box");

        // 3) And those same pixels must be the untouched source video.
        using (var src = new FfmpegFrameDecoder(Video(SourceClip)))
        {
            var sbuf = new byte[W * H * 3];
            Assert.IsTrue(src.TryReadNext(sbuf, out _, out _), "source decode failed");
            foreach (var (x, y) in new (int, int)[]
            {
                (Px0 - 6, Py0 + 108),
                (Px0 + Pw + 6, Py0 + 108),
                (Px0 + 195, Py0 - 6),
                (Px0 + 195, Py0 + Ph + 6),
                (10, 10),
            })
            {
                int d = MaxChannelDiff(f, sbuf, x, y);
                Assert.IsTrue(d <= 2,
                    $"video pixel ({x},{y}) changed by {d} — blend must not touch pixels outside the panel");
            }
        }
    }

    [TestMethod]
    public void Burn_Lossy_ProducesDecodableMp4()
    {
        var res = BurnLossy();
        Assert.AreEqual(Frames, res.Frames);
        Assert.IsTrue(res.OutputPath.EndsWith(".mp4", StringComparison.OrdinalIgnoreCase));
        Assert.IsTrue(new FileInfo(res.OutputPath).Length > 10_000, "output looks empty");

        var frames = DecodeAll(res.OutputPath);
        Assert.AreEqual(Frames, frames.Count, "lossy output must keep the frame count");

        // The panel must still land at the anchor in the lossy path too.
        byte[] f = frames[0];
        Assert.IsTrue(IsPanelBg(f, Px0 + 6, Py0 + 6) ||
                      Math.Abs(f[(Py0 + 6) * W * 3 + (Px0 + 6) * 3] - PanelBg[0]) <= 8,
            "lossy burn: panel corner not at its anchor");
        Assert.IsFalse(IsPanelBg(f, Px0 - 6, Py0 + 108),
            "lossy burn: pixel left of the panel anchor is PanelBg");
    }
}
